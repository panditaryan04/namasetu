"""Latency benchmark of the main API paths, in process, on a fresh database seeded from the SAMPLE data.

Usage: python scripts/bench.py [--n 200]   (or `make bench`)

Writes docs/bench.md and the README block between the BENCH markers. The numbers include FastAPI routing,
validation, auth and serialisation (TestClient), but not network or a reverse proxy; Postgres in Docker
adds a little database latency. Rate limits are lifted for the run.
"""

from __future__ import annotations

import argparse
import os
import platform
import statistics
import sys
import time
from pathlib import Path
from urllib.parse import quote

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))

START = "<!-- BENCH:START (generated by scripts/bench.py; do not edit by hand) -->"
END = "<!-- BENCH:END -->"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=200, help="timed requests per path")
    args = ap.parse_args()

    from run_eval import fresh_environment

    os.environ.setdefault("LOG_LEVEL", "WARNING")
    fresh_environment()

    from fastapi.testclient import TestClient

    from app.core import ratelimit
    from app.core.security import create_token
    from app.db.migrate import upgrade_to_head
    from app.db.seed import load_bundle, seed_sample
    from app.db.session import get_sessionmaker
    from app.db.users import ensure_demo_users
    from app.main import create_app

    upgrade_to_head()
    with get_sessionmaker()() as session:
        seed_sample(session, load_bundle(use_embedded=True))
        ensure_demo_users(session)
        session.commit()
    for group in ratelimit.LIMITS:
        ratelimit.LIMITS[group] = (10**9, 60.0)

    token = create_token("clinician", "clinician", "access")
    paths: list[tuple[str, str, str, dict[str, object] | None]] = [
        ("Autocomplete (IAST prefix)", "GET", "/search/autocomplete?q=amla", None),
        (
            "Autocomplete (Devanagari)",
            "GET",
            "/search/autocomplete?q=%E0%A4%9C%E0%A5%8D%E0%A4%B5%E0%A4%B0",
            None,
        ),
        ("Map free text (English)", "POST", "/map", {"text": "acidity"}),
        ("Map free text (Devanagari)", "POST", "/map", {"text": "आमवात"}),
        ("Map free text (typo)", "POST", "/map", {"text": "Amavta"}),
        ("Map by NAMASTE code", "POST", "/map", {"code": "SAMPLE-AYU-0009"}),
        (
            "ConceptMap $translate",
            "GET",
            "/fhir/ConceptMap/$translate?system={namaste}&code=SAMPLE-AYU-0001",
            None,
        ),
        ("ValueSet $expand (filter)", "GET", "/fhir/ValueSet/namaste-ayurveda/$expand?filter=pitta", None),
        ("Medicine search (brand)", "GET", "/medications/search?q=Combiflam", None),
        (
            "Interaction check vs patient",
            "POST",
            "/medications/check",
            {"medication_codes": ["SAMPLE-MED-A008"], "patient_id": "test-patient-01"},
        ),
    ]
    rows = []
    with TestClient(create_app(), headers={"Authorization": f"Bearer {token}"}) as c:
        namaste = quote(c.get("/fhir/CodeSystem/namaste").json()["url"], safe="")
        for label, method, raw_path, body in paths:
            path = raw_path.replace("{namaste}", namaste)
            for _ in range(10):  # warm-up: caches, first-use imports
                c.request(method, path, json=body)
            times = []
            for _ in range(args.n):
                t = time.perf_counter()
                r = c.request(method, path, json=body)
                times.append((time.perf_counter() - t) * 1000)
                if r.status_code != 200:
                    print(f"{label}: HTTP {r.status_code} {r.text[:200]}", file=sys.stderr)
                    return 1
            times.sort()
            rows.append(
                (
                    label,
                    statistics.median(times),
                    times[int(0.95 * len(times)) - 1],
                    times[int(0.99 * len(times)) - 1],
                )
            )

    env = (
        f"{platform.system()} {platform.release()}, {platform.processor() or platform.machine()}, "
        f"{os.cpu_count()} logical CPUs, Python {platform.python_version()}, SQLite, "
        f"{args.n} timed requests per path after 10 warm-up"
    )
    table = [
        "| Path | p50 (ms) | p95 (ms) | p99 (ms) |",
        "|---|---:|---:|---:|",
        *(f"| {label} | {p50:.1f} | {p95:.1f} | {p99:.1f} |" for label, p50, p95, p99 in rows),
    ]
    docs = ROOT.parent / "docs"
    (docs / "bench.md").write_text(
        "\n".join(
            [
                "# Latency benchmark",
                "",
                "> Generated by `python backend/scripts/bench.py`. Do not edit by hand.",
                "",
                f"Environment: {env}.",
                "",
                "In-process (FastAPI TestClient) on a fresh SAMPLE database: routing, validation, auth and "
                "serialisation are included; network and reverse proxy are not. SAMPLE data is small, "
                "so these numbers do not predict latency on the full NAMASTE and ICD-11 releases.",
                "",
                *table,
                "",
            ]
        ),
        encoding="utf-8",
        newline="\n",
    )
    readme = ROOT.parent / "README.md"
    text = readme.read_text(encoding="utf-8")
    if START in text and END in text:
        head, rest = text.split(START, 1)
        _, tail = rest.split(END, 1)
        block = "\n".join([START, "", f"_{env}._", "", *table, "", END])
        readme.write_text(head + block + tail, encoding="utf-8", newline="\n")
    print("\n".join(table))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

"""Render an evaluation run as Markdown (docs/eval-results.md and the README summary between markers)."""

from __future__ import annotations

from typing import Any

README_START = "<!-- EVAL:START (generated by scripts/run_eval.py; do not edit by hand) -->"
README_END = "<!-- EVAL:END -->"
RANK_COLS = [
    ("top1", "Top-1"),
    ("top1_ci95", "Top-1 95% CI"),
    ("top5", "Top-5"),
    ("mrr", "MRR"),
    ("coverage", "Coverage"),
]
GATE_COLS = [
    ("high_band_precision", "High-band precision"),
    ("high_band_rate", "High band"),
    ("review_queue_rate", "Review queue"),
    ("no_match_rate", "No match"),
    ("top1_shown", "Correct & shown"),
    ("relationship_accuracy", "Relationship acc."),
]


def fmt(v: Any) -> str:
    if v is None:
        return "—"
    if isinstance(v, list) and len(v) == 2:
        return f"{v[0]:.2f}–{v[1]:.2f}"
    if isinstance(v, float):
        if v in (0.0, 1.0):
            return f"{v:.1f}"
        return f"{v:.2g}" if abs(v) < 0.001 else f"{v:.3f}".rstrip("0").rstrip(".")
    return str(v)


def table(rows: dict[str, dict[str, Any]], cols: list[tuple[str, str]], first: str) -> list[str]:
    out = [f"| {first} | n | " + " | ".join(h for _, h in cols) + " |", "|---|---:|" + "---:|" * len(cols)]
    for name, m in rows.items():
        out.append(
            f"| {name} | {m.get('queries', '—')} | " + " | ".join(fmt(m.get(k)) for k, _ in cols) + " |"
        )
    return out


def summary_rows(out: dict[str, Any]) -> list[tuple[str, str]]:
    s, r = out["summary"], out["results"]
    meds = r["medication"]
    inter = meds["interactions"]
    dup = inter["by_kind"]["duplicate"]
    hybrid = r["intercomparison"]["systems"]["Hybrid"]
    return [
        ("Held-out TEST queries (Stage-0 baseline off)", str(s["test_queries"])),
        (
            "Hybrid top-1 / top-5 / MRR",
            f"{fmt(s['hybrid_top1'])} / {fmt(s['hybrid_top5'])} / {fmt(s['hybrid_mrr'])}",
        ),
        ("Hybrid top-1, 95% Wilson interval", fmt(hybrid["top1_ci95"])),
        ("Exact-match baseline top-1", fmt(s["exact_top1"])),
        ("High-band precision", fmt(s["high_band_precision"])),
        ("Expected calibration error (TEST pairs)", fmt(s["ece"])),
        ("Safety checks failing (must be 0)", f"{s['safety_failures']} of {len(r['safety']['checks'])}"),
        ("FHIR resources validated in-process / errors", f"{s['fhir_resources']} / {s['fhir_errors']}"),
        ("Brand typo (1 edit) accuracy", fmt(s["brand_typo_accuracy"])),
        ("Unknown brands falsely resolved", str(s["brand_false_resolutions"])),
        (
            "Free-text medication lines resolved",
            f"{meds['line_resolution']['correct']}/{meds['line_resolution']['cases']}",
        ),
        (
            f"Interaction alerts precision / recall ({inter['cases']} cases)",
            f"{fmt(s['interaction_precision'])} / {fmt(s['interaction_recall'])}",
        ),
        ("Duplicate-salt alerts precision / recall", f"{fmt(dup['precision'])} / {fmt(dup['recall'])}"),
    ]


def readme_block(out: dict[str, Any]) -> str:
    lines = [
        README_START,
        "",
        f"Latest evaluation on SAMPLE data · model `{out['model_version']}` · semantic stage "
        f"`{out['summary']['semantic_method']}` · releases {', '.join(f'`{x}`' for x in out['dataset_releases'])}.",
        "",
        "| Measure | Result |",
        "|---|---|",
        *(f"| {k} | {v} |" for k, v in summary_rows(out)),
        "",
        "Full tables (intercomparison, ablation, per-script robustness, calibration, safety): "
        "[docs/eval-results.md](docs/eval-results.md).",
        "",
        README_END,
    ]
    return "\n".join(lines)


def replace_block(text: str, block: str) -> str:
    if README_START in text and README_END in text:
        head, rest = text.split(README_START, 1)
        _, tail = rest.split(README_END, 1)
        return head + block + tail
    raise ValueError("README markers not found")


def markdown(out: dict[str, Any]) -> str:
    r = out["results"]
    ic = r["intercomparison"]["systems"]
    cal = r["calibration"]
    safety = r["safety"]
    meds = r["medication"]
    L: list[str] = [
        "# Evaluation results",
        "",
        "> Generated by `python backend/scripts/run_eval.py` from a fresh database seeded with the SAMPLE data. "
        "Do not edit by hand.",
        "> SAMPLE — illustrative, not official. The gold sets were written by the team; with this few queries the "
        "numbers show that the pipeline works end to end, not independent accuracy. Read the 95% intervals.",
        "",
        f"- Model: `{out['model_version']}`; semantic stage: `{out['summary']['semantic_method']}`",
        f"- Dataset releases: {', '.join(f'`{x}`' for x in out['dataset_releases'])}",
        f"- Split: {r['split']['train']} train / {r['split']['test']} test gold pairs. {r['split']['note']}",
        f"- Run time: {out['duration_s']} s",
        "",
        "## Summary",
        "",
        "| Measure | Result |",
        "|---|---|",
        *(f"| {k} | {v} |" for k, v in summary_rows(out)),
        "",
        "## 1. Intercomparison (TEST split)",
        "",
        "Each system ranks every ICD-11 TM2 target for the NAMASTE concept. *Exact*: identical normalised term. "
        "*Lexical*: token overlap, transliteration off. *Transliteration + Lexical*: best of exact, lexical and "
        "phonetic-folding scores. *Semantic*: the semantic stage alone. *Hybrid*: the full pipeline.",
        "",
        *table(ic, RANK_COLS, "System"),
        "",
        "Gate behaviour of the hybrid pipeline:",
        "",
        *table({"Hybrid": ic["Hybrid"]}, GATE_COLS, "System"),
        "",
        "## 2. Ablation (TEST split; the ranker is retrained without the removed stage)",
        "",
        *table(r["ablation"], RANK_COLS[:4] + GATE_COLS[:1] + GATE_COLS[3:], "Configuration"),
        "",
        "## 3. Robustness by script (query typed as free text, incl. query → NAMASTE resolution)",
        "",
        "Typos are 1–2 seeded character edits (substitution, deletion or transposition; never the first letter).",
        "",
        "TEST split:",
        "",
        *table(
            r["robustness"],
            RANK_COLS[:4]
            + [
                ("resolved_to_correct_namaste", "Resolved to NAMASTE"),
                ("resolved_to_wrong_namaste", "Resolved to wrong concept"),
                ("top1_shown", "Correct & shown"),
            ],
            "Script",
        ),
        "",
        "All gold pairs (train rows were seen by the ranker, so this is optimistic):",
        "",
        *table(
            r["robustness_all_gold"],
            RANK_COLS[:4]
            + [
                ("resolved_to_correct_namaste", "Resolved to NAMASTE"),
                ("resolved_to_wrong_namaste", "Resolved to wrong concept"),
                ("top1_shown", "Correct & shown"),
            ],
            "Script",
        ),
        "",
        "## 4. Calibration",
        "",
        f"- Thresholds: T_HIGH = {cal['thresholds']['high']}, T_LOW = {cal['thresholds']['low']} "
        f"({cal['thresholds'].get('source', '')}); method: {cal['threshold_method']}",
        f"- TEST candidate pairs: {cal['test_pairs']}; expected calibration error {fmt(cal['test_expected_calibration_error'])}; "
        f"Brier score {fmt(cal['brier_score'])}",
        "",
        "| Confidence bin | Pairs | Mean predicted | Observed correct |",
        "|---|---:|---:|---:|",
        *(
            f"| {b['lower']:.1f}–{b['upper']:.1f} | {b['count']} | {b['mean_predicted']:.3f} | {b['observed']:.3f} |"
            for b in cal["test_reliability"]
            if b["count"]
        ),
        "",
        "## 5. Safety checks (all must be 0)",
        "",
        "| Check | Failures |",
        "|---|---:|",
        *(f"| {k.replace('_', ' ')} | {v} |" for k, v in safety["checks"].items()),
        "",
        "Scope: " + ", ".join(f"{k.replace('_', ' ')} {v}" for k, v in safety["scope"].items()) + ".",
        "",
        "### FHIR conformance (in-process structural + binding validation)",
        "",
        "| Resource | Count | Errors | Warnings |",
        "|---|---:|---:|---:|",
        *(
            f"| {k} | {v['resources']} | {v['errors']} | {v['warnings']} |"
            for k, v in safety["fhir_conformance"].items()
        ),
        "",
        "The HL7 FHIR Validator (4.0.1) runs separately over `docs/fhir-examples/` in CI.",
        "",
        "## 6. Medications (reference only)",
        "",
        "| Brand resolution | Cases | Result |",
        "|---|---:|---:|",
        *(
            f"| {k} | {v['cases']} | {fmt(v['accuracy'])} |"
            for k, v in meds["brands"].items()
            if isinstance(v, dict) and "accuracy" in v
        ),
        f"| not in catalogue (false resolutions, must be 0) | {meds['brands']['not in catalogue']['cases']} | "
        f"{meds['brands']['not in catalogue']['false_resolutions']} |",
        "",
        "| Ingredient names (salts, herbs, minerals) | Cases | Accuracy |",
        "|---|---:|---:|",
        *(
            f"| {k} | {v['cases']} | {fmt(v['accuracy'])} |"
            for k, v in meds["ingredient_names"]["groups"].items()
        ),
        "",
        f"Names shared by more than one ingredient (either answer accepted): "
        f"{', '.join(meds['ingredient_names']['shared_names']) or 'none'}.",
        "",
        f"Free-text medication lines: {meds['line_resolution']['correct']}/{meds['line_resolution']['cases']}.",
        "",
        "| Interaction alerts | TP | FP | FN | Precision | Recall |",
        "|---|---:|---:|---:|---:|---:|",
        *(
            f"| {k} | {v['true_positives']} | {v['false_positives']} | {v['false_negatives']} | "
            f"{fmt(v['precision'])} | {fmt(v['recall'])} |"
            for k, v in meds["interactions"]["by_kind"].items()
        ),
        "",
        "## 7. Failures",
        "",
    ]
    fails = [(n, f) for n, s in ic.items() for f in s.get("failures", [])]
    fails += [(f"robustness: {n}", f) for n, s in r["robustness"].items() for f in s.get("failures", [])]
    if not fails:
        L.append("None.")
    else:
        L += ["| Where | Query | Gold | Rank | Top candidates |", "|---|---|---|---:|---|"]
        for where, f in fails[:60]:
            L.append(f"| {where} | {f['query']} | {f['gold']} | {f['rank'] or '—'} | {', '.join(f['top'])} |")
    L += ["", "## Timings (s)", "", ", ".join(f"{k} {v}" for k, v in r["timings_s"].items()), ""]
    return "\n".join(L)

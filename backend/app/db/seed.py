"""Seed the bundled SAMPLE datasets (idempotent: unchanged sources are skipped by checksum).

Postgres mode reads the individual files in data/sample/. LOCAL mode (SQLite) reads the single
data/sample/embedded_db.json, which scripts/build_embedded_db.py generates from those same files.
Both feed identical loaders, so the resulting database is the same.

Run: python -m app.db.seed
"""

from __future__ import annotations

import csv
import io
import json
import logging
from pathlib import Path
from typing import Any

import yaml
from sqlalchemy import select
from sqlalchemy.orm import Session

from app.core.config import SAMPLE_DIR, get_settings
from app.core.logging import configure_logging
from app.db.models import (
    SOURCE_ICD11,
    SOURCE_NAMASTE,
    SYSTEM_BIO,
    SYSTEM_NAMASTE,
    SYSTEM_TM2,
    Patient,
    PatientMedication,
)
from app.db.session import get_sessionmaker
from app.db.users import ensure_demo_users
from app.engine.service import engine_holder
from app.ingest.crosswalk import import_official_crosswalk
from app.ingest.gold_loader import parse_gold
from app.ingest.icd11_client import MockICD11Client
from app.ingest.namaste_loader import parse_namaste
from app.ingest.release import ReleaseResult, ingest_concepts, ingest_gold, ingest_synonyms
from app.ingest.synonyms_loader import parse_synonyms
from app.medication.catalog import catalog_holder
from app.medication.constituents import ingest_interaction_data
from app.medication.history import import_bundle
from app.medication.ingest import ingest_medications
from app.workflow.review import enqueue_unmapped

logger = logging.getLogger("namasetu.seed")

EMBEDDED_FILE = "embedded_db.json"
SAMPLE_LABEL = "SAMPLE — illustrative, not official"


def _csv_rows(path: Path) -> list[dict[str, str]]:
    return list(csv.DictReader(io.StringIO(path.read_text(encoding="utf-8-sig"))))


def build_embedded_bundle(sample_dir: Path = SAMPLE_DIR) -> dict[str, Any]:
    """Collect every sample source into one JSON-serialisable bundle."""
    return {
        "_label": f"{SAMPLE_LABEL}. Generated by scripts/build_embedded_db.py; do not edit by hand.",
        "namaste_version": "SAMPLE-1",
        "namaste_rows": _csv_rows(sample_dir / "namaste_sample.csv"),
        "icd11_tm2": json.loads((sample_dir / "icd11_tm2_sample.json").read_text(encoding="utf-8")),
        "icd11_bio": json.loads((sample_dir / "icd11_bio_sample.json").read_text(encoding="utf-8")),
        "synonyms": yaml.safe_load((sample_dir / "synonyms.yaml").read_text(encoding="utf-8")),
        "gold_version": "SAMPLE-1",
        "gold_rows": _csv_rows(sample_dir / "gold_mappings.csv"),
        "medications_version": "SAMPLE-1",
        "medications": {
            "synonyms": yaml.safe_load((sample_dir / "medication_synonyms.yaml").read_text(encoding="utf-8")),
            "formulations": _csv_rows(sample_dir / "ayush_formulations_sample.csv"),
            "drugs": _csv_rows(sample_dir / "biomed_drugs_sample.csv"),
            "brands": _csv_rows(sample_dir / "brand_to_salt_sample.csv"),
            "links": _csv_rows(sample_dir / "condition_medication_links_sample.csv"),
        },
        "interactions_version": "SAMPLE-1",
        "interactions": {
            "constituents": _csv_rows(sample_dir / "constituents_sample.csv"),
            "rules": _csv_rows(sample_dir / "interactions_sample.csv"),
        },
        "synthetic_patients": json.loads(
            (sample_dir / "synthetic_patients.json").read_text(encoding="utf-8")
        ),
    }


def load_bundle(use_embedded: bool, sample_dir: Path = SAMPLE_DIR) -> dict[str, Any]:
    if use_embedded:
        data: dict[str, Any] = json.loads((sample_dir / EMBEDDED_FILE).read_text(encoding="utf-8"))
        return data
    return build_embedded_bundle(sample_dir)


def seed_sample(
    session: Session, bundle: dict[str, Any], crosswalk_split: str | None = None
) -> list[ReleaseResult]:
    results: list[ReleaseResult] = []

    concepts, report = parse_namaste(bundle["namaste_rows"])
    results.append(
        ingest_concepts(
            session,
            source=SOURCE_NAMASTE,
            version=bundle["namaste_version"],
            systems=[SYSTEM_NAMASTE],
            concepts=concepts,
            report=report,
            is_sample=True,
        )
    )

    snap = MockICD11Client(bundle["icd11_tm2"], bundle["icd11_bio"]).fetch()
    results.append(
        ingest_concepts(
            session,
            source=SOURCE_ICD11,
            version=snap.release,
            systems=[SYSTEM_TM2, SYSTEM_BIO],
            concepts=snap.tm2 + snap.bio,
            links=snap.links,
            report=snap.report,
            is_sample=True,
        )
    )

    synonyms, syn_report = parse_synonyms(bundle["synonyms"])
    results.append(ingest_synonyms(session, synonyms, syn_report, is_sample=True))

    gold, gold_report = parse_gold(bundle["gold_rows"])
    results.append(ingest_gold(session, gold, gold_report, version=bundle["gold_version"], is_sample=True))

    # Official crosswalk -> Approved Mapping Store (train split only by default; see ingest/crosswalk.py).
    import_official_crosswalk(session, crosswalk_split or get_settings().stage0_gold_split)

    # Medication reference data (needs the condition codes above for link validation).
    results.append(
        ingest_medications(
            session, bundle["medications"], version=bundle["medications_version"], is_sample=True
        )
    )
    # Cited constituents + interactions, then SYNTHETIC patients whose history uses the normal import path.
    results.append(
        ingest_interaction_data(
            session,
            bundle["interactions"]["constituents"],
            bundle["interactions"]["rules"],
            version=bundle["interactions_version"],
            is_sample=True,
        )
    )
    seed_synthetic_patients(session, bundle["synthetic_patients"])
    return results


def seed_synthetic_patients(session: Session, data: dict[str, Any]) -> int:
    """Create the SYNTHETIC demo patients and import their FHIR history once (idempotent)."""
    session.flush()
    catalog = catalog_holder.get(session)
    created = 0
    for p in data.get("patients", []):
        patient = session.get(Patient, p["id"])
        if patient is None:
            patient = Patient(
                id=p["id"], display=p["display"], abha_number=p["abha_number"], is_synthetic=True
            )
            session.add(patient)
            session.flush()
            created += 1
        has_history = session.scalar(
            select(PatientMedication.id).where(PatientMedication.patient_id == patient.id)
        )
        if not has_history:
            import_bundle(
                session, catalog, patient, p["bundle"], actor="system", role="system", purpose="TREAT"
            )
    return created


def main() -> None:
    settings = get_settings()
    configure_logging(settings.log_level)
    use_embedded = settings.db_mode == "sqlite-local"
    bundle = load_bundle(use_embedded)
    with get_sessionmaker()() as session:
        results = seed_sample(session, bundle)
        created = ensure_demo_users(session)
        session.commit()
    if created:
        logger.info("demo users", extra={"extra_fields": {"created": created}})
    # Queue every code the official crosswalk does not cover, so clinicians can confirm or correct it.
    with get_sessionmaker()() as session:
        queued = enqueue_unmapped(session, engine_holder.get(session))
        session.commit()
    logger.info("review backfill", extra={"extra_fields": {"queued": queued}})
    for r in results:
        logger.info(
            "seed",
            extra={
                "extra_fields": {
                    "release": r.release.tag,
                    "status": "unchanged" if r.skipped else "ingested",
                    "rows": r.release.row_count,
                    "source_file": EMBEDDED_FILE if use_embedded else "data/sample/*",
                }
            },
        )


if __name__ == "__main__":
    main()
